            warnings: list[str] = []
            files = extract_archive_excel_files(archive_path, root / "extract", warnings)
            self.assertEqual(files, [])
            self.assertEqual(len(warnings), 1)
            self.assertIn("压缩包带密码", warnings[0])
            self.assertFalse(any((root / "extract").glob("archive_*")))


