    def test_corrupt_non_zip_archives_never_leave_partial_results(self) -> None:
        with tempfile.TemporaryDirectory() as temp_root:
            root = Path(temp_root)
            source = root / "normal.xlsx"
            source.write_bytes(_make_xlsx_bytes())

            valid_7z = root / "valid.7z"
            with py7zr.SevenZipFile(valid_7z, "w") as archive:
                archive.write(source, arcname=source.name)
            valid_tar_gz = root / "valid.tar.gz"
            with tarfile.open(valid_tar_gz, "w:gz") as archive:
                archive.add(source, arcname=source.name)

            corrupt_payloads = {
                "corrupt.rar": _RAR_EQUIVALENCE_FIXTURE[: len(_RAR_EQUIVALENCE_FIXTURE) // 2],
                "corrupt.7z": valid_7z.read_bytes()[: valid_7z.stat().st_size // 2],
                "corrupt.tar.gz": valid_tar_gz.read_bytes()[: valid_tar_gz.stat().st_size // 2],
            }
            for index, (name, payload) in enumerate(corrupt_payloads.items()):
                archive_path = root / name
                archive_path.write_bytes(payload)
                extract_root = root / f"corrupt-extract-{index}"
                warnings: list[str] = []
                files = extract_archive_excel_files(archive_path, extract_root, warnings)
                with self.subTest(archive=name):
                    self.assertEqual(files, [])
                    self.assertEqual(len(warnings), 1)
                    self.assertIn("解压失败", warnings[0])
                    self.assertFalse(any(extract_root.glob("archive_*")))

    def test_encrypted_7z_is_rejected_without_partial_results(self) -> None:
        with tempfile.TemporaryDirectory() as temp_root:
            root = Path(temp_root)
            source = root / "normal.xlsx"
            source.write_bytes(_make_xlsx_bytes())
            archive_path = root / "encrypted.7z"
